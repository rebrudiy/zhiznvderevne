package metrics

import "github.com/prometheus/client_golang/prometheus"

var (
	HTTPRequests = prometheus.NewCounterVec(
		prometheus.CounterOpts{
			Name: "blog_http_requests_total",
			Help: "Total HTTP requests",
		},
		[]string{"method", "path", "status"},
	)
	HTTPDuration = prometheus.NewHistogramVec(
		prometheus.HistogramOpts{
			Name:    "blog_http_request_duration_seconds",
			Help:    "HTTP request duration in seconds",
			Buckets: prometheus.DefBuckets,
		},
		[]string{"method", "path"},
	)
	GeneratedPosts = prometheus.NewCounter(
		prometheus.CounterOpts{
			Name: "blog_generated_posts_total",
			Help: "Total posts generated by worker",
		},
	)
	GenerationErrors = prometheus.NewCounter(
		prometheus.CounterOpts{
			Name: "blog_generation_errors_total",
			Help: "Total errors while generating posts",
		},
	)
)

func Register(reg *prometheus.Registry) {
	reg.MustRegister(HTTPRequests, HTTPDuration, GeneratedPosts, GenerationErrors)
}
